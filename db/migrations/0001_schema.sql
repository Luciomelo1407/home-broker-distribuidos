-- Schema do Simulador de Bolsa, derivado de docs/simulador-bolsa.dbml.
-- Os CHECKs são a "segunda barreira" (docs/simulador-bolsa-modelo-explicado.md,
-- seção "Regras de integridade no banco"): violar um deles é bug do Motor, não rejeição.

-- ---------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------

CREATE TYPE tipo_investidor AS ENUM ('humano', 'agente');

CREATE TYPE perfil_agente AS ENUM ('conservador', 'agressivo');

CREATE TYPE lado_ordem AS ENUM ('compra', 'venda');

CREATE TYPE status_ordem AS ENUM ('ABERTA', 'PARCIAL', 'EXECUTADA', 'CANCELADA', 'REJEITADA');

-- ---------------------------------------------------------------
-- investidores: humanos e agentes, com o saldo (RF-001, RF-009, RF-019)
-- ---------------------------------------------------------------

CREATE TABLE investidores (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario     varchar(50)     NOT NULL,
    senha_hash       varchar(255)    NOT NULL,
    tipo             tipo_investidor NOT NULL DEFAULT 'humano',
    perfil           perfil_agente,
    saldo_disponivel decimal(15, 2)  NOT NULL,
    saldo_reservado  decimal(15, 2)  NOT NULL DEFAULT 0,
    criado_em        timestamp       NOT NULL DEFAULT now(),

    CONSTRAINT uq_investidores_nome_usuario UNIQUE (nome_usuario),
    -- RNF-01
    CONSTRAINT ck_investidores_saldo_disponivel CHECK (saldo_disponivel >= 0),
    CONSTRAINT ck_investidores_saldo_reservado CHECK (saldo_reservado >= 0),
    -- RF-020: perfil só existe para agentes
    CONSTRAINT ck_investidores_perfil_so_agente CHECK (tipo = 'agente' OR perfil IS NULL)
);

-- ---------------------------------------------------------------
-- ativos: conjunto fixo de ações virtuais (RF-006, RF-017, S-01)
-- ---------------------------------------------------------------

CREATE TABLE ativos (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           varchar(10)    NOT NULL,
    nome_empresa     varchar(100)   NOT NULL,
    preco_inicial    decimal(15, 2) NOT NULL,
    preco_referencia decimal(15, 2) NOT NULL,
    preco_atual      decimal(15, 2) NOT NULL,
    volume_negociado bigint         NOT NULL DEFAULT 0,
    atualizado_em    timestamp      NOT NULL DEFAULT now(),

    CONSTRAINT uq_ativos_codigo UNIQUE (codigo),
    -- RF-017
    CONSTRAINT ck_ativos_preco_inicial CHECK (preco_inicial > 0),
    CONSTRAINT ck_ativos_preco_atual CHECK (preco_atual > 0),
    -- Não está na tabela do modelo explicado: é a base da variação % do RF-006 (divisor).
    CONSTRAINT ck_ativos_preco_referencia CHECK (preco_referencia > 0)
);

-- ---------------------------------------------------------------
-- posicoes: carteira, uma linha por investidor × ativo (RF-005, RF-010)
-- ---------------------------------------------------------------

CREATE TABLE posicoes (
    investidor_id         integer        NOT NULL REFERENCES investidores (id),
    ativo_id              integer        NOT NULL REFERENCES ativos (id),
    quantidade_disponivel integer        NOT NULL,
    quantidade_reservada  integer        NOT NULL DEFAULT 0,
    preco_medio           decimal(15, 4) NOT NULL DEFAULT 0,
    atualizado_em         timestamp      NOT NULL DEFAULT now(),

    PRIMARY KEY (investidor_id, ativo_id),
    -- RNF-01
    CONSTRAINT ck_posicoes_quantidade_disponivel CHECK (quantidade_disponivel >= 0),
    CONSTRAINT ck_posicoes_quantidade_reservada CHECK (quantidade_reservada >= 0)
);

-- ---------------------------------------------------------------
-- ordens: cada pedido de compra/venda e também o livro de ofertas
-- (livro = ordens ABERTA ou PARCIAL). O id é o desempate por tempo (RF-014).
-- ---------------------------------------------------------------

CREATE TABLE ordens (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investidor_id        integer        NOT NULL REFERENCES investidores (id),
    ativo_id             integer        NOT NULL REFERENCES ativos (id),
    client_order_id      uuid           NOT NULL,
    stream_id            varchar(32),
    lado                 lado_ordem     NOT NULL,
    preco_limite         decimal(15, 2) NOT NULL,
    quantidade           integer        NOT NULL,
    quantidade_executada integer        NOT NULL DEFAULT 0,
    status               status_ordem   NOT NULL,
    motivo_rejeicao      varchar(255),
    criado_em            timestamp      NOT NULL DEFAULT now(),
    atualizado_em        timestamp      NOT NULL DEFAULT now(),

    CONSTRAINT uq_ordens_stream_id UNIQUE (stream_id),
    -- Reenvio após timeout nunca gera ordem dupla (system design §4)
    CONSTRAINT uq_ordens_cliente_idempotencia UNIQUE (investidor_id, client_order_id),
    -- RNF-07
    CONSTRAINT ck_ordens_preco_limite CHECK (preco_limite > 0),
    CONSTRAINT ck_ordens_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_ordens_quantidade_executada CHECK (quantidade_executada BETWEEN 0 AND quantidade),
    -- RF-011: motivo preenchido quando, e só quando, a ordem foi rejeitada
    CONSTRAINT ck_ordens_motivo_rejeicao CHECK ((status = 'REJEITADA') = (motivo_rejeicao IS NOT NULL))
);

-- Reconstrução do livro após queda do Motor (RF-024)
CREATE INDEX idx_ordens_livro ON ordens (ativo_id, lado, status);

-- Histórico do investidor (RF-008)
CREATE INDEX idx_ordens_historico ON ordens (investidor_id, criado_em);

-- ---------------------------------------------------------------
-- negocios: cada execução entre uma compra e uma venda (RF-015, RF-016)
-- ---------------------------------------------------------------

CREATE TABLE negocios (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id        integer        NOT NULL REFERENCES ativos (id),
    ordem_compra_id bigint         NOT NULL REFERENCES ordens (id),
    ordem_venda_id  bigint         NOT NULL REFERENCES ordens (id),
    preco           decimal(15, 2) NOT NULL,
    quantidade      integer        NOT NULL,
    executado_em    timestamp      NOT NULL DEFAULT now(),

    -- RF-016
    CONSTRAINT ck_negocios_preco CHECK (preco > 0),
    CONSTRAINT ck_negocios_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_negocios_ordens_distintas CHECK (ordem_compra_id <> ordem_venda_id)
);

CREATE INDEX idx_negocios_ativo ON negocios (ativo_id, executado_em);
CREATE INDEX idx_negocios_ordem_compra ON negocios (ordem_compra_id);
CREATE INDEX idx_negocios_ordem_venda ON negocios (ordem_venda_id);
